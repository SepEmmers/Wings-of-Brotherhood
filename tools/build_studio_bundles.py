def classify_sprite(fname):
    n = fname.lower()
    if n.startswith("portrait_"):
        return "Portraits"
    if n.startswith("boy") or n.startswith("npc_") or n.startswith("clara") or n.startswith("anna"):
        return "Characters & NPCs"
    if n.startswith("dragon_") or "hatchling" in n or "virelai" in n or "kestrel" in n:
        return "Dragons"
    if n.startswith("bldg_") or n.startswith("city_") or n.startswith("building_"):
        return "Buildings"
    if n.startswith("cs_"):
        return "Cutscenes"
    if n.startswith("ui_") or n.startswith("icon_") or "heart" in n or "butcher" in n or "mason" in n:
        return "UI & Icons"
    if n.startswith("tile_"):
        return "Tiles & Ground"
    if any(w in n for w in ["crypt", "sarcophagus", "shrine", "altar", "candle", "spikes", "dart", "plate", "vent", "relic", "relief", "tapestry", "lectern", "library", "grapple", "boulder", "sconce"]):
        return "Dungeon & Shrine"
    if n.startswith("furn_"):
        return "Interior Furniture"
    return "Props & World"


def read_png_dims(raw_bytes):
    if len(raw_bytes) >= 24 and raw_bytes[:8] == b"\x89PNG\r\n\x1a\n":
        w, h = struct.unpack(">II", raw_bytes[16:24])
        return int(w), int(h)
    return 16, 16


def build_sprites_bundle():
    palette_list, ramps = load_palette()
    sprites = {}
    portraits = []
    if os.path.isdir(SPRITES_DIR):
        for fname in sorted(os.listdir(SPRITES_DIR)):
            if not fname.lower().endswith(".png"):
                continue
            fpath = os.path.join(SPRITES_DIR, fname)
            with open(fpath, "rb") as f:
                raw = f.read()
            w, h = read_png_dims(raw)
            b64 = base64.b64encode(raw).decode("ascii")
            sprites[fname] = {
                "w": w,
                "h": h,
                "cat": classify_sprite(fname),
                "b64": f"data:image/png;base64,{b64}",
            }
            if fname.startswith("portrait_"):
                portraits.append(fname)

    out_path = os.path.join(STUDIO_DATA_DIR, "sprites_bundle.js")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/build_studio_bundles.py\n")
        f.write("window.STUDIO_PALETTE = " + json.dumps(palette_list) + ";\n")
        f.write("window.STUDIO_RAMPS = " + json.dumps(ramps) + ";\n")
        f.write("window.STUDIO_PORTRAITS = " + json.dumps(portraits) + ";\n")
        f.write("window.STUDIO_SPRITES_BUNDLE = " + json.dumps(sprites) + ";\n")
    return len(sprites), os.path.getsize(out_path)


def extract_balanced_dicts(text):
    """Yields (start_idx, end_idx, dict_str) for top-level-ish {...} dict blocks."""
    i = 0
    n = len(text)
    in_str = False
    str_ch = ""
    esc = False
    depth = 0
    start = -1
    results = []
    while i < n:
        ch = text[i]
        if in_str:
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == str_ch:
                in_str = False
        else:
            if ch == "#" and depth == 0:
                nl = text.find("\n", i)
                i = nl if nl != -1 else n
                continue
            if ch in ('"', "'"):
                in_str = True
                str_ch = ch
            elif ch == "{":
                if depth == 0:
                    start = i
                depth += 1
            elif ch == "}":
                if depth > 0:
                    depth -= 1
                    if depth == 0 and start != -1:
                        results.append((start, i + 1, text[start : i + 1]))
                        start = -1
        i += 1
    return results


def parse_gd_str_value(block, key):
    """Extracts a string value for `"key": ...` handling GDScript literals and `%` args."""
    pat = re.compile(r'"' + re.escape(key) + r'"\s*:\s*')
    m = pat.search(block)
    if not m:
        return None
    idx = m.end()
    n = len(block)
    while idx < n and block[idx] in " \t":
        idx += 1
    if idx >= n:
        return None
    if block[idx] == '"':
        j = idx + 1
        out = []
        esc = False
        while j < n:
            c = block[j]
            if esc:
                if c == "n":
                    out.append("\n")
                elif c == '"':
                    out.append('"')
                elif c == "\\":
                    out.append("\\")
                else:
                    out.append(c)
                esc = False
            elif c == "\\":
                esc = True
            elif c == '"':
                return "".join(out)
            else:
                out.append(c)
            j += 1
        return "".join(out)
    # Expression like GameState.player_name or GameState.gold_dragon_name
    end_m = re.search(r'[,}\n]', block[idx:])
    expr = block[idx : idx + end_m.start()].strip() if end_m else block[idx:].strip()
    if "gold_dragon_name" in expr:
        return "%DRAGON%"
    if "player_name" in expr:
        return "%PLAYER%"
    return expr


def parse_gd_bool_value(block, key):
    m = re.search(r'"' + re.escape(key) + r'"\s*:\s*(true|false)', block)
    if m:
        return m.group(1) == "true"
    return False


