def build_dialogue_bundle():
    entries = []
    speakers_set = set()
    regions_set = set()
    seen_ids = set()

    gd_files = []
    for root, _, files in os.walk(SCRIPTS_DIR):
        for fn in sorted(files):
            if fn.endswith(".gd"):
                gd_files.append(os.path.join(root, fn))

    for fpath in sorted(gd_files):
        rel_path = os.path.relpath(fpath, ROOT).replace("\\", "/")
        if rel_path.startswith("scripts/tools/"):
            continue
        with open(fpath, "r", encoding="utf-8") as f:
            content = f.read()

        region_lbl = infer_region_label(rel_path)

        # Find nested arrays or line-by-line dicts for dialogue & barks
        # Also detect simple inline dicts inside nested arrays by scanning all `{...}` blocks
        # Extract all inner `{...}` that have no inner `{`
        for m in re.finditer(r'\{[^{}]+\}', content):
            block = m.group(0)
            line_no = content[: m.start()].count("\n") + 1
            spk = parse_gd_str_value(block, "speaker")
            txt = parse_gd_str_value(block, "text")
            bark = parse_gd_str_value(block, "bark")
            name = parse_gd_str_value(block, "name")

            if spk is not None and txt is not None:
                port = parse_gd_str_value(block, "portrait") or ""
                tele = parse_gd_bool_value(block, "telepathic")
                if not port and (tele or "Hatchling" in spk or "%DRAGON%" in spk):
                    port = "portrait_hatchling_stage1.png"
                elif "player_name" in port or "get_boy_portrait" in port:
                    port = "portrait_boy_neutral.png"
                elif not port.endswith(".png"):
                    port = "portrait_boy_neutral.png"

                eid = f"{os.path.basename(rel_path)}:{line_no}:{spk}"
                idx_suffix = 1
                base_eid = eid
                while eid in seen_ids:
                    idx_suffix += 1
                    eid = f"{base_eid}_{idx_suffix}"
                seen_ids.add(eid)

                entries.append({
                    "id": eid,
                    "kind": "dialogue",
                    "region": region_lbl,
                    "file": rel_path,
                    "line": line_no,
                    "speaker": spk,
                    "portrait": port,
                    "telepathic": tele,
                    "text": txt,
                })
                speakers_set.add(spk)
                regions_set.add(region_lbl)
            elif bark is not None and bark.strip():
                npc_name = name or "Townsfolk"
                tex = parse_gd_str_value(block, "tex") or ""
                npc_id = parse_gd_str_value(block, "id") or f"bark_{line_no}"
                eid = f"{os.path.basename(rel_path)}:{line_no}:{npc_id}"
                while eid in seen_ids:
                    eid += "_x"
                seen_ids.add(eid)
                port = "portrait_watchman.png"
                if "fishwife" in tex or "apothecary" in tex:
                    port = "portrait_maren.png"
                elif "monk" in tex:
                    port = "portrait_priest.png"
                elif "sailor" in tex:
                    port = "portrait_shipmaster.png"
                elif "cooper" in tex:
                    port = "portrait_quartermaster.png"
                elif "apprentice" in tex:
                    port = "portrait_hendrick.png"
                elif "mason" in tex:
                    port = "portrait_uncle.png"

                entries.append({
                    "id": eid,
                    "kind": "bark",
                    "region": region_lbl,
                    "file": rel_path,
                    "line": line_no,
                    "speaker": npc_name,
                    "portrait": port,
                    "telepathic": False,
                    "text": bark,
                    "npc_id": npc_id,
                    "tex": tex,
                })
                speakers_set.add(npc_name)
                regions_set.add(region_lbl)

    # Also extract ItemCatalog entries
    item_cat_path = os.path.join(SCRIPTS_DIR, "data", "ItemCatalog.gd")
    if os.path.isfile(item_cat_path):
        with open(item_cat_path, "r", encoding="utf-8") as f:
            ic_src = f.read()
        for m in re.finditer(r'\{[^{}]+\}', ic_src):
            block = m.group(0)
            cat = parse_gd_str_value(block, "category")
            desc = parse_gd_str_value(block, "desc")
            icon = parse_gd_str_value(block, "icon")
            if cat and desc:
                line_no = ic_src[: m.start()].count("\n") + 1
                eid = f"ItemCatalog.gd:{line_no}:{cat}"
                entries.append({
                    "id": eid,
                    "kind": "item",
                    "region": "Item Lore Catalog",
                    "file": "scripts/data/ItemCatalog.gd",
                    "line": line_no,
                    "speaker": cat,
                    "portrait": icon or "icon_knot.png",
                    "telepathic": False,
                    "text": desc,
                })
                regions_set.add("Item Lore Catalog")

    out_path = os.path.join(STUDIO_DATA_DIR, "dialogue_bundle.js")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/build_studio_bundles.py\n")
        f.write("window.STUDIO_DIALOGUE_BUNDLE = " + json.dumps(entries, ensure_ascii=False) + ";\n")
        f.write("window.STUDIO_SPEAKERS = " + json.dumps(sorted(speakers_set), ensure_ascii=False) + ";\n")
        f.write("window.STUDIO_DIALOGUE_REGIONS = " + json.dumps(sorted(regions_set), ensure_ascii=False) + ";\n")
    return len(entries)


