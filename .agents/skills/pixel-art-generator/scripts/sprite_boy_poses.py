def _make_boy_carry_egg(grid_lines=None, cloth_overrides=None) -> PixelCanvas:
    egg_legend = {
        **STD_LEGEND,
        "h": "H1", "Z": "O1", "o": "O2", "O": "O3", "Y": "Y2",
    }
    base_legend = {**STD_LEGEND, **(cloth_overrides or {})}
    lines = grid_lines if grid_lines is not None else BOY_CARRY_EGG
    assert len(lines) == 28, f"Expected 28 rows, got {len(lines)}"
    c = PixelCanvas(24, 28)
    for y, line in enumerate(lines):
        assert len(line) == 24, f"Row {y} len {len(line)} != 24: {line}"
        for x, ch in enumerate(line):
            if y >= 13 and ch in ("h", "Z", "o", "O", "Y"):
                key = egg_legend[ch]
            else:
                key = base_legend.get(ch)
            if key is not None:
                c.pset(x, y, key)
    c.add_outline("K", selective_hue=True)
    return c


